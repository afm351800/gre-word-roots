// Bundles data/*.json into words.js. Run: node build.js
// Deck names and order mirror the GRE flashcard app exactly.
const fs = require("fs");
const path = require("path");

const DECKS = [
  ["Common Words", ["I", "II", "III", "IV", "V", "VI", "VII"]],
  ["Basic", ["I", "II", "III", "IV", "V", "VI", "VII", "VIII", "IX"]],
  ["Advanced", ["I", "II", "III", "IV", "V", "VI", "VII", "VIII", "IX"]],
];

const out = [];
const seen = new Map();
for (const [series, numerals] of DECKS) {
  for (const n of numerals) {
    const name = `${series} ${n}`;
    const slug = name.toLowerCase().replace(/ /g, "-");
    const file = path.join(__dirname, "data", slug + ".json");
    if (!fs.existsSync(file)) { console.warn("missing", file); continue; }
    const words = JSON.parse(fs.readFileSync(file, "utf8"));
    for (const w of words) {
      for (const k of ["w", "p", "m", "e", "f", "t"]) if (!w[k]) throw new Error(`${name}: ${w.w} missing ${k}`);
      if (seen.has(w.w)) console.warn(`duplicate ${w.w} in ${name} and ${seen.get(w.w)}`);
      seen.set(w.w, name);
    }
    words.sort((a, b) => a.w.localeCompare(b.w, "en", { sensitivity: "base" }));
    out.push({ name, slug, series, words });
  }
}
const total = out.reduce((s, d) => s + d.words.length, 0);
fs.writeFileSync(path.join(__dirname, "words.js"),
  "// Generated by build.js from data/*.json. Do not edit by hand.\nwindow.DECKS=" + JSON.stringify(out) + ";\n");
console.log(`${out.length} decks, ${total} words`);
